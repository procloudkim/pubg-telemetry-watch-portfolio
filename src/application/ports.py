"""Structural contracts only at real external resource boundaries.

Use cases receive these objects from CLI composition. Values are plain records;
use cases never invoke connection, credential or RDF APIs directly.
"""

from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Mapping, Protocol

Row = Mapping[str, Any]


class Clock(Protocol):
    def now(self, *, timespec: str = "microseconds") -> str: ...
    def perf_counter(self) -> float: ...
    def monotonic(self) -> float: ...
    def sleep(self, seconds: float) -> None: ...


class Environment(Protocol):
    def fingerprint(self) -> str: ...
    def runtime(self) -> dict[str, str]: ...
    def peak_rss_kib(self) -> int: ...
    def request_id(self) -> str: ...


class FileStat(Protocol):
    st_size: int


class Files(Protocol):
    def read_bytes(self, path: Path) -> bytes: ...
    def read_text(self, path: Path, **kwargs) -> str: ...
    def read_json(self, path: Path) -> Any: ...
    def read_checked_bytes(self, path: Path, expected_sha256: str) -> bytes: ...
    def write_bytes(self, path: Path, body: bytes) -> None: ...
    def write_json(self, path: Path, value: Any, *, indent=None) -> None: ...
    def write_once(self, path: Path, body: bytes) -> None: ...
    def hash(self, path: Path) -> str: ...
    def exists(self, path: Path) -> bool: ...
    def is_file(self, path: Path) -> bool: ...
    def stat(self, path: Path) -> FileStat: ...
    def resolve(self, path: Path) -> Path: ...
    def mkdir(self, path: Path, **kwargs) -> None: ...
    def glob(self, path: Path, pattern: str) -> list[Path]: ...
    def rglob(self, path: Path, pattern: str) -> list[Path]: ...
    def unlink(self, path: Path, *, missing_ok=True) -> None: ...
    def link_or_copy(self, source: Path, target: Path) -> None: ...
    def load_events(self, match_id: str, version=None, run_id=None) -> list: ...
    def read_ledger(self, path: Path) -> list[dict]: ...
    def append_ledger(self, path: Path, row: dict) -> None: ...


class BatchInputSource(Protocol):
    def read_inputs(
        self, manifest_path: Path, source_root: Path
    ) -> tuple[str, str, list[dict]]: ...
    def load(self, job: Row) -> list[dict]: ...


class HttpReply(Protocol):
    status_code: int
    content: bytes

    def raise_for_status(self) -> None: ...
    def json(self) -> Any: ...


class PubgTransport(Protocol):
    def authorize(self) -> None: ...
    def request(self, path: str) -> HttpReply: ...
    def get(self, path: str, raw_path=None) -> Any: ...
    def download_telemetry(
        self, url: str, match_id: str, *, version="v1", run_id=None, compatibility_copy=True
    ) -> str: ...


class AuditEngine(Protocol):
    def calculate(
        self, run_id: str, manifest: dict, observations: list, source_hashes: dict, sql_path: Path
    ) -> dict: ...


class SemanticEngine(Protocol):
    def load_contract(self, root: Path) -> dict: ...
    def runtime(self) -> dict[str, str]: ...
    def evaluate(
        self,
        run_id: str,
        sources: dict,
        contract: dict,
        experiment: str,
        rule: str,
        season: str,
        graph_summary: dict,
        sql_summary: dict,
        oracle_tokens: set[str],
    ) -> dict: ...


class OperationsPresentation(Protocol):
    def render_operations(self, batch_id: str, summary: dict) -> bytes: ...
    def render_review(self, signals: list, manifest: list, generated_at: str) -> bytes: ...


class OperationsStore(Protocol):
    def transaction(self) -> AbstractContextManager[None]: ...

    def read_snapshot(self) -> AbstractContextManager[None]: ...

    def begin(self, *, immediate=False) -> None: ...

    def commit(self) -> None: ...

    def rollback(self) -> None: ...

    def fatal_error(self, error: Any) -> str | None: ...

    def batch(self, batch_id: str) -> Row | None: ...

    def add_batch(self, values: Any) -> None: ...

    def job(self, job_id: str) -> Row | None: ...

    def add_job(self, values: Any) -> None: ...

    def link_job(self, batch_id: str, job_id: str) -> None: ...

    def recover(self, now: str) -> None: ...

    def next_attempt(self, job_id: str) -> int: ...

    def claim(self, job_id: str, attempt_no: Any, now: str) -> None: ...

    def project(self, keys: Any, combat_rows: Any) -> None: ...

    def measures(self, job_id: str, protocol: str) -> list[dict]: ...

    def add_measures(self, job_id: str, measures: Any) -> None: ...

    def add_signals(self, job_id: str, signals: Any) -> None: ...

    def add_case(self, case_id: str, job_id: str, signal: Any, created: str) -> None: ...

    def succeed(
        self,
        job_id: str,
        attempt_no: Any,
        finished: str,
        event_count: Any,
        player_count: Any,
        result_hash: Any,
        times: Any,
        rss: Any,
    ) -> None: ...

    def fail(
        self,
        job_id: str,
        attempt_no: Any,
        now: str,
        stage: str,
        code: str,
        elapsed: Any,
        times: Any,
        rss: Any,
    ) -> None: ...

    def record_timing(self, job_id: str, attempt_no: Any, times: Any, elapsed: Any) -> None: ...

    def queued_jobs(self, batch_id: str) -> list[Row]: ...

    def retry(self, batch_id: str, job_id: str) -> int: ...

    def jobs(self, batch_id: str) -> list[dict]: ...

    def attempts(self, batch_id: str) -> list[dict]: ...

    def review_list(self, batch_id: str, state: str) -> list[dict]: ...

    def review_evidence(self, case_id: str) -> Row | None: ...

    def review_history(self, case_id: str) -> list[dict]: ...

    def review_case(self, case_id: str) -> Row | None: ...

    def next_review_sequence(self, case_id: str) -> int: ...

    def change_review(self, case_id: str, state: str, now: str, history: Any) -> None: ...

    def report_rows(self, batch_id: str) -> tuple[list, list, list, list, list]: ...
